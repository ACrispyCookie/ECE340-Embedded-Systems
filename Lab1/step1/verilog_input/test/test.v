`timescale 1ns / 1ps
module tb_fpadd;
reg clk;
reg rst;
reg [31:0] A;
reg [31:0] B;
wire [31:0] out;

localparam CLK_PERIOD = 10;
always #(CLK_PERIOD/2) clk=~clk;

fpadd_single DUT(.clk(clk), .reset(rst), .reg_A(A), .reg_B(B), .out(out));

initial begin
    clk=0;
    rst=0;
    #300 rst=1;
    #100 rst=0;
    A=32'h3f800000; B=32'h3f800000; // 1.0 + 1.0 = 2.0
    #100 A=32'h3f800000; B=32'hc0000000; // 1.0 + -2.0 = -1.0
    #100 A=32'h3f800000; B=32'h40000000; // 1.0 + 2.0 = 3.0
    #100 A=32'h3f800000; B=32'h40400000; // 1.0 + 3.0 = 4.0
    #100 A=32'h3f800000; B=32'h3f000000; // 1.0 + 0.5 = 1.5
    #100 A=32'h3f800000; B=32'h3f400000; // 1.0 + 0.75 = 1.75
    #100 A=32'h3f800000; B=32'h3f600000; // 1.0 + 0.875 = 1.875
    #100 A=32'h3f800000; B=32'h3f700000; // 1.0 + 0.9375 = 1.9375
    #100 A=32'h3f800000; B=32'h3f780000; // 1.0 + 0.984375 = 1.984375
    #100 A=32'h3f800000; B=32'h3f7c0000; // 1.0 + 0.9921875 = 1.9921875
    #100 A=32'h3f800000; B=32'h3f7e0000; // 1.0 + 0.99609375 = 1.99609375
    #100 A=32'h3f800000; B=32'h3f7f0000; // 1.0 + 0.998046875 = 1.998046875
    #100 A=32'hc0000000; B=32'hbf800000; // -2.0 + -1.0 = -3.0
    #100 A=32'hbf800000; B=32'hc0400000; // -1.0 + -3.0 = -4.0
    #100 A=32'h3f800000; B=32'hbf800000; // 1.0 + -1.0 = 0.0
    #100 A=32'hbf800000; B=32'hbf000000; // -1.0 + -0.5 = -1.5
    #100 A=32'hbf400000; B=32'hbf600000; // -0.75 + -0.875 = -1.625
    #100 A=32'h40000000; B=32'hbf800000; // 2.0 + -1.0 = 1.0
    #100 A=32'hc0400000; B=32'h3f800000; // -3.0 + 1.0 = -2.0
    #100 A=32'h40400000; B=32'hbf000000; // 3.0 + -0.5 = 2.5
    #100 A=32'hbf400000; B=32'h3f000000; // -0.75 + 0.5 = -0.25
    #100 A=32'h3f800000; B=32'hbf400000; // 1.0 + -0.75 = 0.25
    #100 A=32'hbf000000; B=32'h3f400000; // -0.5 + 0.75 = 0.25
    #100 A=32'hc0000000; B=32'h3f000000; // -2.0 + 0.5 = -1.5
    #100 A=32'hbfc66666; B=32'h3fc7ae14; // 0.5 + -2.0 = -1.5


    #100 $finish;
end

endmodule